#!/usr/bin/env bash
# ==============================================================================
# Script: deploy.sh (Predictive Distribution System Automated Deployment)
# Usage: ./deploy.sh
# ==============================================================================

set -euo pipefail

GREEN='\033[0;32m'
BLUE='\033[0;34m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEPLOY_DIR="${ROOT_DIR}/deploy"
ENV_FILE="${DEPLOY_DIR}/.env.prod"
COMPOSE_FILE="${DEPLOY_DIR}/docker-compose.prod.yml"

cd "$ROOT_DIR"

echo -e "${BLUE}======================================================"
echo -e " DINZIN: Predictive Distribution System Deployment"
echo -e "======================================================${NC}"

# 1. First-time auto-configuration: prompt for domain & auto-generate secrets
if [ ! -f "$ENV_FILE" ]; then
    echo -e "${YELLOW}No production environment found. Starting quick interactive setup...${NC}\n"

    read -rp "Enter your Application Domain (e.g., pds.yourdomain.com or localhost): " APP_DOMAIN
    APP_DOMAIN="${APP_DOMAIN:-localhost}"

    read -rp "Enter Admin Email for Let's Encrypt SSL: " ACME_EMAIL
    ACME_EMAIL="${ACME_EMAIL:-admin@${APP_DOMAIN}}"

    echo -e "${BLUE}Generating cryptographically secure encryption and auth keys...${NC}"
    DB_PASSWORD=$(openssl rand -hex 20)
    MASTER_ENCRYPTION_KEY=$(openssl rand -hex 32)
    JWT_SECRET=$(openssl rand -base64 32)

    cat << EOF > "$ENV_FILE"
# ==============================================================================
# Auto-generated by deploy.sh on $(date)
# ==============================================================================

# Application Domain & Reverse Proxy SSL
APP_DOMAIN=${APP_DOMAIN}
ACME_EMAIL=${ACME_EMAIL}

# Database (PostgreSQL 16)
POSTGRES_DB=pds_production
POSTGRES_USER=pds_admin
POSTGRES_PASSWORD=${DB_PASSWORD}

# Cache & Queues (Valkey / Redis)
REDIS_URL=redis://valkey:6379

# Master Encryption Key (32-byte hex for AES-256-GCM secret vault)
MASTER_ENCRYPTION_KEY=${MASTER_ENCRYPTION_KEY}

# JWT Authentication Secret
JWT_SECRET=${JWT_SECRET}
EOF

    echo -e "${GREEN}✔ Created deploy/.env.prod with secure AES-256 and JWT secrets.${NC}\n"
else
    echo -e "${GREEN}✔ Production configuration loaded from deploy/.env.prod.${NC}"
fi

# 2. Pull Git updates if running inside a Git clone
if [ -d ".git" ]; then
    CURRENT_BRANCH=$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo "main")
    echo -e "${BLUE}Checking for repository updates on ${CURRENT_BRANCH}...${NC}"
    git pull origin "$CURRENT_BRANCH" 2>/dev/null || echo -e "${YELLOW}Notice: Git pull skipped (working offline or detached HEAD).${NC}"
fi

# 3. Build & pull Docker containers
echo -e "${BLUE}Building container images (Fastify API, Next.js Web, BullMQ Worker)...${NC}"
docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE" build --pull

# 4. Start Database & Cache first
echo -e "${BLUE}Starting PostgreSQL and Valkey services...${NC}"
docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE" up -d postgres valkey

# 5. Wait for Database Readiness
echo -e "${BLUE}Waiting for PostgreSQL to be ready...${NC}"
MAX_TRIES=30
COUNT=0
DB_USER=$(grep -E '^POSTGRES_USER=' "$ENV_FILE" | cut -d '=' -f2 || echo "pds_admin")
DB_NAME=$(grep -E '^POSTGRES_DB=' "$ENV_FILE" | cut -d '=' -f2 || echo "pds_production")

until docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE" exec -T postgres pg_isready -U "$DB_USER" -d "$DB_NAME" >/dev/null 2>&1; do
    COUNT=$((COUNT + 1))
    if [ $COUNT -ge $MAX_TRIES ]; then
        echo -e "${RED}✖ PostgreSQL did not become ready in time.${NC}" >&2
        exit 1
    fi
    sleep 2
done
echo -e "${GREEN}✔ PostgreSQL is ready.${NC}"

# 6. Run Drizzle ORM Migrations
echo -e "${BLUE}Executing database migrations...${NC}"
docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE" run --rm api npm run --workspace=packages/db migrate 2>/dev/null || \
docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE" run --rm api npx drizzle-kit migrate 2>/dev/null || \
echo -e "${YELLOW}Notice: Migrations skipped or already up to date.${NC}"

# 7. Start remaining services (API, Worker, Web, Caddy)
echo -e "${BLUE}Starting all services (Caddy, API, Worker, Next.js Web)...${NC}"
docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE" up -d --remove-orphans

# 8. Setup Nightly Database Backup Cron (Automated)
mkdir -p "${ROOT_DIR}/backups"
cat << EOF > /etc/cron.d/pds-backup 2>/dev/null || true
# Nightly backup for DINZIN Predictive Distribution System
0 2 * * * root docker compose --env-file ${ENV_FILE} -f ${COMPOSE_FILE} exec -T postgres pg_dump -U ${DB_USER} ${DB_NAME} | gzip > ${ROOT_DIR}/backups/db_\$(date +\%Y\%m\%d_\%H\%M\%S).sql.gz && find ${ROOT_DIR}/backups/ -type f -name "db_*.sql.gz" -mtime +14 -delete
EOF

# 9. Prune old dangling images
docker image prune -f >/dev/null 2>&1 || true

# 10. Display Status & URLs
echo -e "\n${GREEN}======================================================"
echo -e " ✔ DINZIN: Deployment Successful!"
echo -e "======================================================${NC}"
docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE" ps

DEPLOYED_DOMAIN=$(grep -E '^APP_DOMAIN=' "$ENV_FILE" | cut -d '=' -f2)
echo -e "\n${BLUE}Web Dashboard:${NC}  https://${DEPLOYED_DOMAIN}"
echo -e "${BLUE}API Ingestion:${NC}  https://${DEPLOYED_DOMAIN}/api"
echo -e "${BLUE}Health Check:${NC}   https://${DEPLOYED_DOMAIN}/api/health (or Caddy root)"
echo -e "${BLUE}View Logs:${NC}      docker compose --env-file deploy/.env.prod -f deploy/docker-compose.prod.yml logs -f\n"

